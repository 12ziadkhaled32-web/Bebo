export function getAzkarPool(period: AzkarPeriod): ZekrItem[] {
  return period === 'morning' ? MORNING_AZKAR : EVENING_AZKAR;
}

export function selectAzkarByCount(period: AzkarPeriod, requestedCount: number): ZekrItem[] {
  const pool = getAzkarPool(period);
  if (!Number.isFinite(requestedCount)) return [];
  const safeCount = Math.max(1, Math.min(pool.length, Math.floor(requestedCount)));
  return pool.slice(0, safeCount);
}

