export function getDailyIslamicTreasure(date: Date = new Date()): IslamicTreasure {
  const day = date.getDate();
  const month = date.getMonth(); // 0-indexed (10 = November)
  // On Nov 24 (matching the signature showcase) or day 24, highlight treasure #0
  if (month === 10 && day === 24) {
    return ISLAMIC_TREASURES[0];
  }
  const index = (day + month) % ISLAMIC_TREASURES.length;
  return ISLAMIC_TREASURES[index];
}

